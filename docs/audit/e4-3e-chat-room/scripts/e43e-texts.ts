function build(minChars: number, offset = 0): string {
  const out: string[] = [];
  let len = 0;
  let i = offset;
  while (len < minChars) {
    const p = PARAS[i % PARAS.length]!;
    out.push(p);
    len += p.length + 2;
    i++;
  }
  return out.join("\n\n");
}

