import { chromium } from "playwright-core";
import fs from "fs";
const BASE = process.env.BASE;
const fx = JSON.parse(fs.readFileSync("/tmp/e43h-fixtures.json", "utf8"));
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: "ko-KR" });
await ctx.addCookies([{ name: "session", value: fx.tokens.std, url: BASE }]);
const p = await ctx.newPage();
const watchFor = (sel, ms) => p.waitForFunction((s) => !!document.querySelector(s), sel, { timeout: ms }).then(() => true).catch(() => false);
await p.goto(BASE + "/settings", { waitUntil: "load" }); await p.waitForTimeout(1200);
let w = watchFor("[data-chat-resume-veil]", 5000);
await p.locator("aside a[data-chat-resume]").first().click();
await p.waitForURL((u) => new URL(u).pathname.startsWith("/chat/"), { timeout: 15000 }).catch(() => {});
const normalVeil = await w; await p.waitForTimeout(2000);
const room = await p.evaluate(() => document.querySelector("[data-chat-room-character]")?.getAttribute("data-chat-room-character") ?? null);
await p.goto(BASE + "/settings", { waitUntil: "load" }); await p.waitForTimeout(1200);
const w1 = watchFor("[data-chat-resume-veil]", 2500), w2 = watchFor(".menu-veil", 2500);
await p.locator('aside a[href="/verify"]').first().click();
await p.waitForURL((u) => new URL(u).pathname === "/verify", { timeout: 15000 }).catch(() => {});
console.log(JSON.stringify({ base: BASE, normal: { chatVeil: normalVeil, roomCharacter: room }, masked: { landed: new URL(p.url()).pathname, chatVeil: await w1, menuVeil: await w2 } }));
await b.close();
