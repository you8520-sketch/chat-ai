import { chromium } from "playwright-core";
import fs from "fs";
import Database from "better-sqlite3";
const BASE = process.env.BASE;
const fx = JSON.parse(fs.readFileSync("/tmp/e43h-fixtures.json", "utf8"));
const db = new Database("/tmp/e43h-data/app.db");
const uid = db.prepare("SELECT id FROM users WHERE email='adultflag@e43.local'").get().id;
const titles = () => db.prepare("SELECT id, character_id, title FROM chats WHERE user_id=? ORDER BY id").all(uid).map((r) => `${r.id}:c${r.character_id}:${JSON.stringify(r.title)}`);
const out = { titlesBefore: titles() };
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: "ko-KR" });
await ctx.addCookies([{ name: "session", value: fx.tokens.adultflag, url: BASE }]);
const p = await ctx.newPage();
await p.goto(BASE + "/chats", { waitUntil: "load" }); await p.waitForTimeout(1200);
const adult = () => p.locator(".chats-page-grid article", { hasText: "2개 대화" });
// rename: untouched save is blocked, empty prefill
await adult().first().locator("button", { hasText: "대화 선택" }).click();
const dlg = p.locator('[role="dialog"]').first();
await dlg.getByRole("button", { name: "이름 변경" }).first().click();
const input = dlg.getByPlaceholder("새 대화방 이름");
out.rename = { prefill: await input.inputValue(), saveDisabledWhenEmpty: await dlg.getByRole("button", { name: "저장" }).isDisabled() };
await input.fill("나만 아는 이름");
out.rename.saveEnabledAfterTyping = !(await dlg.getByRole("button", { name: "저장" }).isDisabled());
const w = p.waitForResponse((r) => r.url().includes("/api/chat/session") && r.request().method() === "PATCH");
await dlg.getByRole("button", { name: "저장" }).click();
out.rename.patchStatus = (await w).status();
await p.waitForTimeout(1500);
out.rename.dialogTextAfter = (await dlg.innerText().catch(() => "")).replace(/\n+/g, " / ");
out.titlesAfterRename = titles();
await dlg.getByRole("button", { name: "닫기" }).click().catch(() => {});
// cancel path leaves title untouched
await adult().first().locator("button", { hasText: "대화 선택" }).click();
await dlg.getByRole("button", { name: "이름 변경" }).nth(1).click();
await dlg.getByRole("button", { name: "취소" }).click();
out.titlesAfterCancel = titles();
await dlg.getByRole("button", { name: "닫기" }).click();
out.singleDeleteButtonsForMasked = await (async () => { await adult().first().locator("button", { hasText: "대화 선택" }).click(); const n = await dlg.getByRole("button", { name: /삭제/ }).count(); await dlg.getByRole("button", { name: "닫기" }).click(); return n; })();
// bulk delete the masked groups (selection mode)
await p.getByRole("button", { name: "선택 삭제" }).click();
const selBtns = p.getByRole("button", { name: "성인 콘텐츠 선택" });
out.selectableMasked = await selBtns.count();
await selBtns.first().click();
out.selectedLabel = (await p.getByRole("button", { name: /선택한 대화 삭제/ }).innerText());
const delW = p.waitForResponse((r) => r.url().includes("/api/chat/session") && r.request().method() === "DELETE");
await p.getByRole("button", { name: /선택한 대화 삭제/ }).click();
await p.getByRole("button", { name: "삭제", exact: true }).click();
out.bulkDelete = { status: (await delW).status() };
await p.waitForTimeout(2000);
out.titlesAfterDelete = titles();
out.cardsAfter = await p.locator(".chats-page-grid article").evaluateAll((as) => as.map((a) => a.innerText.replace(/\n+/g, " / ").slice(0, 70)));
out.otherUsersChats = db.prepare("SELECT COUNT(*) n FROM chats WHERE user_id<>?").get(uid).n;
await b.close();
console.log(JSON.stringify(out, null, 1));
