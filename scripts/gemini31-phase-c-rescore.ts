import fs from "node:fs";
import path from "node:path";

import {
  buildPhaseC1Diagnosis,
  classifyCacheDrop,
  normalizeLegacyTurnRecord,
  type FixtureKind,
  type PhaseCTurnRecord,
} from "./lib/gemini31PhaseCAnalyzer";

const ARTIFACT_DIR = path.join(process.cwd(), "docs/audits/gemini31-phase-c-ttft");
const OUT_ARTIFACT = path.join(ARTIFACT_DIR, "report-c1.json");
const METRIC_AUDIT = path.join(ARTIFACT_DIR, "METRIC_AUDIT.md");

function loadFixture(kind: FixtureKind): PhaseCTurnRecord[] {
  const p = path.join(ARTIFACT_DIR, `turns-${kind}.jsonl`);
  const lines = fs.readFileSync(p, "utf8").trim().split("\n").filter(Boolean);
  const turns = lines.map((l) => normalizeLegacyTurnRecord(JSON.parse(l) as Record<string, unknown>));
  for (let i = 0; i < turns.length; i++) {
    turns[i]!.cache_drop_class = classifyCacheDrop(i > 0 ? turns[i - 1]! : null, turns[i]!);
  }
  return turns;
}

