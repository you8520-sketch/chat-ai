function main() {
  const fixtures = (["A", "B", "C"] as FixtureKind[]).map((f) => ({
    fixture: f,
    turns: loadFixture(f),
  }));
  const allTurns = fixtures.flatMap((f) => f.turns);

  const diagnosis = buildPhaseC1Diagnosis(allTurns, {
    legacyReportContentionCount: 7,
    stageTimingAvailable: allTurns.some((t) => t.provider_wait_ms != null),
  });

  const report = {
    generatedAt: new Date().toISOString(),
    phase: "C.1",
    readOnly: true,
    rescoredFrom: "docs/audits/gemini31-phase-c-ttft/turns-{A,B,C}.jsonl",
    turnCount: allTurns.length,
    fixtures: Object.fromEntries(
      fixtures.map((f) => [
        f.fixture,
        {
          turnCount: f.turns.length,
          turns: f.turns,
        },
      ])
    ),
    ...diagnosis,
  };

  fs.writeFileSync(OUT_ARTIFACT, JSON.stringify(report, null, 2));
  writeMetricAudit();
  console.log(JSON.stringify(diagnosis, null, 2));
  console.log("Wrote", OUT_ARTIFACT);
  console.log("Wrote", METRIC_AUDIT);
}

main();
